// Coverage audit of the problem bank: ladders vs. targets, concept coverage, curated-list and
// company coverage, and high-priority problems left out. Writes content/AUDIT.md.
// Usage: node scripts/content/audit.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { TOPICS, ladderTotals } from '../../src/js/data/taxonomy.js';

const ROOT = new URL('../../', import.meta.url).pathname;
const { problems } = JSON.parse(await readFile(ROOT + 'content/index/problems.json', 'utf8'));
const selected = problems.filter((p) => p.status !== 'indexed');
const BANDS = ['Easy', 'Medium', 'Hard'];
const pct = (a, b) => (b ? Math.round((100 * a) / b) : 0) + '%';
const count = (arr, band) => arr.filter((p) => p.difficulty === band).length;

const out = [];
const w = (s = '') => out.push(s);
const totals = ladderTotals(TOPICS);
const gaps = [];

w('# Content audit');
w();
w(`Generated by \`node scripts/content/audit.mjs\` from \`content/index/problems.json\` (${problems.length} problems indexed).`);
w();
w('## Summary');
w();
w('| | Easy | Medium | Hard | Total |');
w('|---|---|---|---|---|');
w(`| Target | ${totals.easy} | ${totals.medium} | ${totals.hard} | ${totals.all} |`);
w(`| Selected | ${count(selected, 'Easy')} | ${count(selected, 'Medium')} | ${count(selected, 'Hard')} | ${selected.length} |`);
w(`| Indexed pool | ${count(problems, 'Easy')} | ${count(problems, 'Medium')} | ${count(problems, 'Hard')} | ${problems.length} |`);
w();

w('## Per topic');
w();
w('Ladder = selected / target per band. Pool = indexed candidates in that topic per band.');
w();
w('| Tier | Topic | Ladder E | Ladder M | Ladder H | Concepts covered | Pool E/M/H |');
w('|---|---|---|---|---|---|---|');
for (const t of TOPICS) {
  const mine = selected.filter((p) => p.topic === t.id);
  const pool = problems.filter((p) => p.topic === t.id);
  const target = { Easy: t.ladder.easy, Medium: t.ladder.medium, Hard: t.ladder.hard };
  const cells = BANDS.map((b) => {
    const got = count(mine, b);
    if (got !== target[b]) gaps.push(`${t.title}: ${b} ladder has ${got}, target ${target[b]}`);
    if (count(pool, b) < target[b] * 3) gaps.push(`${t.title}: thin ${b} pool (${count(pool, b)} candidates for ${target[b]} slots)`);
    return `${got}/${target[b]}`;
  });
  const covered = new Set(mine.map((p) => p.concept));
  const missing = t.concepts.filter((c) => !covered.has(c));
  for (const c of missing) gaps.push(`${t.title}: concept \`${c}\` has no selected problem`);
  const conceptCell = `${t.concepts.length - missing.length}/${t.concepts.length}` + (missing.length ? ` (missing: ${missing.join(', ')})` : '');
  w(`| ${t.tier} | ${t.title} | ${cells.join(' | ')} | ${conceptCell} | ${BANDS.map((b) => count(pool, b)).join(' / ')} |`);
}
w();

w('## Curated lists');
w();
for (const [list, size] of [['blind75', 75], ['neetcode150', 150]]) {
  const inList = problems.filter((p) => p.lists.includes(list));
  const picked = inList.filter((p) => p.status !== 'indexed');
  w(`- **${list}**: ${picked.length} / ${inList.length} selected (${pct(picked.length, inList.length)}).`);
  if (inList.length < size) gaps.push(`${list}: only ${inList.length} of ${size} found in the index`);
}
w();
const nc150Missing = problems.filter((p) => p.lists.includes('neetcode150') && p.status === 'indexed');
w(`NeetCode 150 problems not on any ladder (${nc150Missing.length}):`);
w();
w('| Problem | Difficulty | Topic | Companies |');
w('|---|---|---|---|');
for (const p of nc150Missing) w(`| ${p.title} | ${p.difficulty} | ${p.topic} | ${p.companyCount} |`);
w();

w('## Company coverage');
w();
w('For the 15 companies with the most tagged problems: how many of their 30 most frequent problems are on a ladder, and the difficulty mix of those 30.');
w();
const byCompany = new Map();
for (const p of problems) {
  for (const c of p.companies) {
    if (!byCompany.has(c.name)) byCompany.set(c.name, []);
    byCompany.get(c.name).push({ p, frequency: c.frequency });
  }
}
const topCompanies = [...byCompany.entries()].sort((a, b) => b[1].length - a[1].length).slice(0, 15);
w('| Company | Tagged | Top-30 on a ladder | Top-30 Easy/Medium/Hard |');
w('|---|---|---|---|');
for (const [name, list] of topCompanies) {
  const top = list.sort((a, b) => b.frequency - a.frequency).slice(0, 30).map((x) => x.p);
  const onLadder = top.filter((p) => p.status !== 'indexed').length;
  w(`| ${name} | ${list.length} | ${onLadder}/30 (${pct(onLadder, 30)}) | ${BANDS.map((b) => count(top, b)).join(' / ')} |`);
}
w();

w('## High-priority problems not selected');
w();
w('The 30 highest-priority indexed problems that are not on any ladder. Candidates to swap in or to justify leaving out.');
w();
w('| Priority | Problem | Difficulty | Topic | Companies | Lists |');
w('|---|---|---|---|---|---|');
for (const p of problems.filter((x) => x.status === 'indexed').slice(0, 30)) {
  w(`| ${p.priority} | ${p.title} | ${p.difficulty} | ${p.topic} | ${p.companyCount} | ${p.lists.filter((l) => l !== 'neetcode-all').join(', ') || '-'} |`);
}
w();

w('## Selected but rarely asked');
w();
const rare = selected.filter((p) => p.companyCount < 3).sort((a, b) => a.companyCount - b.companyCount);
w(`${rare.length} selected problems are tagged by fewer than 3 companies. Fine when they teach a concept nothing else covers; otherwise swap.`);
w();
for (const p of rare) w(`- ${p.title} (${p.topic} / ${p.concept}, ${p.companyCount} companies)`);
w();

w('## Gaps');
w();
if (!gaps.length) w('None found.');
for (const g of gaps) w(`- ${g}`);
w();

await writeFile(ROOT + 'content/AUDIT.md', out.join('\n'));
console.log(`content/AUDIT.md written, ${gaps.length} gaps`);
