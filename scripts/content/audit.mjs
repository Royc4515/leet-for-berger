// Coverage audit of the problem bank: core waves, ladders vs. targets, concept coverage, easy
// entry points, curated-list and company coverage, and what was left out. Writes content/AUDIT.md.
// Usage: node scripts/content/audit.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { TOPICS, ladderTotals } from '../../src/js/data/taxonomy.js';
import { pickVersion, frequencyLookup } from '../../src/js/data/families.js';

const ROOT = new URL('../../', import.meta.url).pathname;
const { problems } = JSON.parse(await readFile(ROOT + 'content/index/problems.json', 'utf8'));
const selection = JSON.parse(await readFile(ROOT + 'content/selection.json', 'utf8'));
const core = problems.filter((p) => p.wave !== null);
const wave1 = core.filter((p) => p.wave === 1);
const wave2 = core.filter((p) => p.wave === 2);
const ladder = problems.filter((p) => p.ladderStep !== null);
const BANDS = ['Easy', 'Medium', 'Hard'];
const pct = (a, b) => (b ? Math.round((100 * a) / b) : 0) + '%';
const count = (arr, band) => arr.filter((p) => p.difficulty === band).length;
const mix = (arr) => BANDS.map((b) => count(arr, b)).join(' / ');
const MIN_EASY_ENTRY = 2;

const out = [];
const w = (s = '') => out.push(s);
const totals = ladderTotals(TOPICS);
const gaps = [];

w('# Content audit');
w();
w(`Generated by \`node scripts/content/audit.mjs\` from \`content/index/problems.json\` (${problems.length} problems indexed). Selection rules: \`content/selection.json\`.`);
w();
w('## Summary');
w();
w('| Set | What it is | Easy / Medium / Hard | Total |');
w('|---|---|---|---|');
w(`| Ladders | Learning path, one ladder per topic, every concept covered | ${mix(ladder)} | ${ladder.length} |`);
w(`| Wave 1 | Learning core: ladders + Blind 75 + NeetCode 150 + easy classics | ${mix(wave1)} | ${wave1.length} |`);
w(`| Wave 2 | Company coverage: asked by ${selection.wave2.minCompanies}+ companies, top ${selection.wave2.topPerCompany} at a top-${selection.wave2.topCompanies} company, or the family version a top company asks | ${mix(wave2)} | ${wave2.length} |`);
w(`| **Core bank** | Everything we author (wave 1 + wave 2) | ${mix(core)} | **${core.length}** |`);
w(`| Index | Everything known, available for later waves | ${mix(problems)} | ${problems.length} |`);
w();
w(`Ladder targets: ${totals.easy} / ${totals.medium} / ${totals.hard} (${totals.all}).`);
w();

w('## Per topic');
w();
w('Ladder = selected / target per band. Core = problems in the core bank for that topic. Easy entry = core Easy problems, the on-ramp before the ladder climbs.');
w();
w('| Tier | Topic | Ladder E | Ladder M | Ladder H | Concepts | Core E/M/H | Pool E/M/H |');
w('|---|---|---|---|---|---|---|---|');
for (const t of TOPICS) {
  const mine = ladder.filter((p) => p.topic === t.id);
  const mineCore = core.filter((p) => p.topic === t.id);
  const pool = problems.filter((p) => p.topic === t.id);
  const target = { Easy: t.ladder.easy, Medium: t.ladder.medium, Hard: t.ladder.hard };
  const cells = BANDS.map((b) => {
    const got = count(mine, b);
    if (got !== target[b]) gaps.push(`${t.title}: ${b} ladder has ${got}, target ${target[b]}`);
    return `${got}/${target[b]}`;
  });
  const covered = new Set(mine.map((p) => p.concept));
  const missing = t.concepts.filter((c) => !covered.has(c));
  for (const c of missing) gaps.push(`${t.title}: concept \`${c}\` has no ladder problem`);
  const easyCore = count(mineCore, 'Easy');
  // Tier 4+ topics are entered through their prerequisites' easy problems, not their own.
  if (t.tier < 4 && easyCore < MIN_EASY_ENTRY) gaps.push(`${t.title}: only ${easyCore} Easy problem(s) in the core bank, below the ${MIN_EASY_ENTRY} needed for a gradual start`);
  const conceptCell = `${t.concepts.length - missing.length}/${t.concepts.length}` + (missing.length ? ` (missing: ${missing.join(', ')})` : '');
  w(`| ${t.tier} | ${t.title} | ${cells.join(' | ')} | ${conceptCell} | ${mix(mineCore)} | ${mix(pool)} |`);
}
w();

w('## Curated lists');
w();
for (const list of ['blind75', 'neetcode150', 'neetcode-all']) {
  const inList = problems.filter((p) => p.lists.includes(list));
  const inCore = inList.filter((p) => p.wave !== null);
  const onLadder = inList.filter((p) => p.ladderStep !== null);
  w(`- **${list}**: ${inCore.length} / ${inList.length} in the core bank (${pct(inCore.length, inList.length)}), ${onLadder.length} on a ladder.`);
}
w();

w('## Company coverage');
w();
w(`For the ${selection.wave2.topCompanies} companies with the most tagged problems: how many of their 30 and 100 most frequent problems are in the core bank.`);
w();
const byCompany = new Map();
for (const p of problems) {
  for (const c of p.companies) {
    if (!byCompany.has(c.name)) byCompany.set(c.name, []);
    byCompany.get(c.name).push({ p, frequency: c.frequency });
  }
}
const topCompanies = [...byCompany.entries()].sort((a, b) => b[1].length - a[1].length).slice(0, selection.wave2.topCompanies);
w('| Company | Tagged | Top 30 in core | Top 100 in core | Top 30 on a ladder |');
w('|---|---|---|---|---|');
for (const [name, list] of topCompanies) {
  const sorted = list.sort((a, b) => b.frequency - a.frequency || a.p.slug.localeCompare(b.p.slug)).map((x) => x.p);
  const top30 = sorted.slice(0, 30);
  const top100 = sorted.slice(0, 100);
  const c30 = top30.filter((p) => p.wave !== null).length;
  const c100 = top100.filter((p) => p.wave !== null).length;
  const l30 = top30.filter((p) => p.ladderStep !== null).length;
  if (c30 < 30) gaps.push(`${name}: ${30 - c30} of its top 30 problems are not in the core bank`);
  w(`| ${name} | ${list.length} | ${c30}/30 | ${c100}/${top100.length} (${pct(c100, top100.length)}) | ${l30}/30 |`);
}
w();

const { families } = JSON.parse(await readFile(ROOT + 'content/families.json', 'utf8'));
const lookup = frequencyLookup(problems);
const bySlug = new Map(problems.map((p) => [p.slug, p]));
const members = families.flatMap((f) => f.members);
w('## Families and company versions');
w();
w(`${families.length} families group ${members.length} problems that share one solution idea. ${members.filter((m) => bySlug.get(m.slug).wave !== null).length} of those versions are in the core bank. A learner targeting a company is shown the version that company asks most.`);
w();
w('Families where a top company is shown a non-canonical version:');
w();
w('| Company | Own versions | Examples |');
w('|---|---|---|');
for (const [name] of topCompanies) {
  const own = families
    .map((f) => ({ f, pick: pickVersion(f, name, lookup) }))
    .filter(({ f, pick }) => pick !== f.members[0].slug);
  const examples = own.slice(0, 4).map(({ pick }) => bySlug.get(pick).title).join(', ');
  w(`| ${name} | ${own.length} / ${families.length} | ${examples || '-'} |`);
}
w();
const showcase = ['lowest-common-ancestor', 'vertical-order', 'calculator', 'palindrome-check', 'parentheses-validity', 'subarray-sum-target'];
const five = topCompanies.slice(0, 5).map(([name]) => name);
w('Sample: which version each company sees.');
w();
w(`| Family | ${five.join(' | ')} |`);
w(`|---|${five.map(() => '---').join('|')}|`);
for (const id of showcase) {
  const f = families.find((x) => x.id === id);
  if (!f) continue;
  w(`| ${f.title} | ${five.map((c) => bySlug.get(pickVersion(f, c, lookup)).title).join(' | ')} |`);
}
w();

w('## Highest-priority problems outside the core bank');
w();
w('The next candidates if the bank grows (a later wave).');
w();
w('| Priority | Problem | Difficulty | Topic | Companies |');
w('|---|---|---|---|---|');
for (const p of problems.filter((x) => x.wave === null).slice(0, 20)) {
  w(`| ${p.priority} | ${p.title} | ${p.difficulty} | ${p.topic} | ${p.companyCount} |`);
}
w();

w('## Ladder problems rarely asked');
w();
const rare = ladder.filter((p) => p.companyCount < 3).sort((a, b) => a.companyCount - b.companyCount);
w(`${rare.length} ladder problems are tagged by fewer than 3 companies. Kept because they teach a concept nothing more common covers.`);
w();
for (const p of rare) w(`- ${p.title} (${p.topic} / ${p.concept}, ${p.companyCount} companies)`);
w();

w('## Gaps');
w();
if (!gaps.length) w('None found.');
for (const g of gaps) w(`- ${g}`);
w();

await writeFile(ROOT + 'content/AUDIT.md', out.join('\n'));
console.log(`content/AUDIT.md written: core ${core.length} (wave 1 ${wave1.length}, wave 2 ${wave2.length}), ${gaps.length} gaps`);
