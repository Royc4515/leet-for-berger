#!/usr/bin/env node
/**
 * Copies the reminder rules into the push Edge Function (ADR 0011), so the phone hears exactly what
 * the bell shows: deploy/supabase/functions/push/lib/ gets progress.js, daily.js, notifications.js
 * and push-plan.js from src/js (imports pointed at their neighbours), and titles.js, the problem
 * titles a reminder may name (from the catalog). An Edge Function deploys its own folder only,
 * so it cannot import from src/js.
 *
 * tests/push-server.test.js fails when the copies are stale.
 * Usage: node scripts/content/build-push.mjs   (after changing any of the sources above)
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import catalog from '../../src/js/problems/catalog.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
/** Where the copies go, relative to the repository root. */
export const PUSH_LIB = 'deploy/supabase/functions/push/lib';

/** [source in the repository, file name in PUSH_LIB] */
const SOURCES = [
  ['src/js/state/progress.js', 'progress.js'],
  ['src/js/data/daily.js', 'daily.js'],
  ['src/js/data/notifications.js', 'notifications.js'],
  ['src/js/data/push-plan.js', 'push-plan.js'],
];

const header = (source) => `// Generated by scripts/content/build-push.mjs from ${source}. Do not edit by hand:\n// run the script after changing the source (tests/push-server.test.js checks it).\n`;

/**
 * The files PUSH_LIB should hold, by name.
 * @returns {Record<string, string>}
 */
export function pushLibFiles() {
  const out = {};
  for (const [source, name] of SOURCES) {
    // All four sit side by side in the function, so the one import that leaves its folder is re-pointed.
    const text = readFileSync(join(ROOT, source), 'utf8').replaceAll("from '../state/progress.js'", "from './progress.js'");
    out[name] = header(source) + text;
  }
  const titles = Object.fromEntries(catalog.map((e) => [e.id, e.title]).sort(([a], [b]) => (a < b ? -1 : 1)));
  out['titles.js'] = `${header('src/js/problems/catalog.js')}/** Problem titles by id, for reminders that name a problem. */\nexport const TITLES = ${JSON.stringify(titles, null, 2)};\n`;
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(join(ROOT, PUSH_LIB), { recursive: true });
  for (const [name, text] of Object.entries(pushLibFiles())) writeFileSync(join(ROOT, PUSH_LIB, name), text);
  console.log(`wrote ${PUSH_LIB}/`);
}
