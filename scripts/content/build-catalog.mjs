#!/usr/bin/env node
/**
 * Writes src/js/problems/catalog.js: one entry per problem (id, title, difficulty, topics, status,
 * kind, browser languages) so the dashboard, learning path, companies and mode setups list problems
 * without importing their modules, which build 10 hidden tests each at import time
 * (docs/adr/0008-lazy-problem-modules.md). tests/catalog.test.js fails when it is stale.
 *
 * Order: existing entries keep their place (the dashboard lists them in catalog order), new
 * problems are appended by id, removed ones are dropped, planned entries come last.
 *
 * Usage: node scripts/content/build-catalog.mjs   (after adding, renaming or retitling a problem)
 */

import { readdirSync, existsSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { hydrate, catalogFields } from '../../src/js/problems/hydrate.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const PROBLEMS_DIR = join(ROOT, 'src/js/problems');
const OUT = join(PROBLEMS_DIR, 'catalog.js');

/**
 * Not authored yet: listed as "Coming soon" so the dashboard shows where the bank is heading.
 * An entry disappears from here on its own once src/js/problems/<id>/problem.js exists.
 * @type {{ id: string, title: string, difficulty: string, topics: string[] }[]}
 */
const PLANNED = [
  { id: 'mirror-check', title: 'Mirror Check (Two Pointers)', difficulty: 'Easy', topics: ['arrays-strings'] },
  { id: 'tree-level-sums', title: 'Tree Level Sums', difficulty: 'Easy', topics: ['trees'] },
  { id: 'lowest-shared-ancestor', title: 'Lowest Shared Ancestor', difficulty: 'Medium', topics: ['trees'] },
  { id: 'k-closest-points', title: 'K Closest Points (Heap)', difficulty: 'Medium', topics: ['arrays-strings'] },
  { id: 'grid-min-path', title: 'Grid Minimum Path', difficulty: 'Medium', topics: ['dp'] },
];

const dirs = readdirSync(PROBLEMS_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(PROBLEMS_DIR, d.name, 'problem.js')))
  .map((d) => d.name);

const previous = existsSync(OUT) ? (await import(pathToFileURL(OUT).href)).default.map((e) => e.id) : [];
const order = [...previous.filter((id) => dirs.includes(id)), ...dirs.filter((id) => !previous.includes(id)).sort()];

const entries = [];
for (const id of order) {
  const mod = await import(pathToFileURL(join(PROBLEMS_DIR, id, 'problem.js')).href);
  const entry = catalogFields(hydrate(mod.default));
  if (entry.id !== id) throw new Error(`${id}/problem.js declares id "${entry.id}"; the id must match the directory`);
  entries.push(entry);
}
for (const p of PLANNED) if (!dirs.includes(p.id)) entries.push({ ...p, status: 'planned' });

const body = [
  '// Generated by scripts/content/build-catalog.mjs from src/js/problems/*/problem.js. Do not edit by hand:',
  '// run the script after adding, renaming or retitling a problem (tests/catalog.test.js checks it).',
  '/** @type {import(\'./hydrate.js\').CatalogEntry[]} */',
  'export default [',
  // One problem per line keeps diffs readable when one problem's fields change.
  ...entries.map((e) => `  ${JSON.stringify(e)},`),
  '];',
  '',
].join('\n');
writeFileSync(OUT, body);
console.log(`${entries.filter((e) => e.status === 'available').length} available + ${entries.filter((e) => e.status === 'planned').length} planned -> src/js/problems/catalog.js`);
