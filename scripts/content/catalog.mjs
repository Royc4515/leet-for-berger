/**
 * Builds the problem catalog (src/js/problems/catalog.js): the metadata the listing views need
 * (dashboard, learning path, companies, modes) without importing any problem module. Importing a
 * problem module builds its hidden tests, which is why the catalog exists (ADR 0008).
 *
 * Shared by scripts/content/build-catalog.mjs (writes the file) and tests/catalog.test.js
 * (checks the shipped file is current).
 */

import { readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

/**
 * The catalog row for one problem module. Only what listing views read: anything else stays in
 * problem.js so the catalog cannot drift from it in ways the sync test would miss.
 * @param {object} problem a problem module's default export
 * @returns {{ id: string, title: string, difficulty: string, topics: string[], sql: boolean }}
 */
export function toCatalogEntry(problem) {
  return {
    id: problem.id,
    title: problem.title,
    difficulty: problem.difficulty,
    topics: [...problem.topics],
    sql: problem.signature?.kind === 'sql',
  };
}

/**
 * Ids with a problem.js under problemsDir, sorted.
 * @param {string} problemsDir
 * @returns {string[]}
 */
export function problemDirs(problemsDir) {
  return readdirSync(problemsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(problemsDir, d.name, 'problem.js')))
    .map((d) => d.name)
    .sort();
}

/**
 * Catalog order: the current order is kept (it is the dashboard's listing order), new problems
 * are appended in alphabetical order and removed ones dropped.
 * @param {string[]} currentIds ids in the shipped catalog, in order
 * @param {string[]} dirIds ids that have a problem folder
 * @returns {string[]}
 */
export function orderIds(currentIds, dirIds) {
  const present = new Set(dirIds);
  const kept = currentIds.filter((id) => present.has(id));
  const seen = new Set(kept);
  return [...kept, ...dirIds.filter((id) => !seen.has(id)).sort()];
}

/**
 * Imports every problem module under problemsDir and returns catalog rows in catalog order.
 * Slow (every module builds its hidden tests), so it runs at build and test time, never in the app.
 * @param {string} problemsDir
 * @param {string[]} currentIds
 */
export async function buildCatalog(problemsDir, currentIds) {
  const ids = orderIds(currentIds, problemDirs(problemsDir));
  const rows = [];
  for (const id of ids) {
    const mod = await import(pathToFileURL(join(problemsDir, id, 'problem.js')).href);
    if (mod.default?.id !== id) throw new Error(`${id}/problem.js exports id "${mod.default?.id}", expected "${id}"`);
    rows.push(toCatalogEntry(mod.default));
  }
  return rows;
}

/**
 * Source text of catalog.js. One problem per line keeps diffs readable.
 * @param {ReturnType<typeof toCatalogEntry>[]} rows
 */
export function renderCatalog(rows) {
  return [
    '// Generated by scripts/content/build-catalog.mjs. Do not edit by hand: run `node scripts/content/build-catalog.mjs`.',
    '// Listing metadata for every shipped problem, so listing views never import a problem module (ADR 0008).',
    '/** @type {{ id: string, title: string, difficulty: string, topics: string[], sql: boolean }[]} */',
    'export const CATALOG = [',
    ...rows.map((r) => `  ${JSON.stringify(r)},`),
    '];',
    '',
  ].join('\n');
}
