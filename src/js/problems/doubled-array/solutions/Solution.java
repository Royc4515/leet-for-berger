class Solution {
    // O(n) - allocate 2n once; index i % n walks nums twice.
    public int[] doubleArray(int[] nums) {
        int n = nums.length;
        int[] ans = new int[n << 1];
        for (int i = 0; i < n << 1; ++i) {
            ans[i] = nums[i % n];
        }
        return ans;
    }
}
